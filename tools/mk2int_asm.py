#!/usr/bin/env python3
# The mkII interrupt test of tools/cscp_suite.sh (mk2int): prints its machine code (at C000h) as hex.
# IM 2 with I = C1h; counts 600 Hz timer (level 2) and VRTC (level 1) interrupts at C200h/C202h over 60
# frames timed by polling 40h bit 5, each handler rewriting E4h.
org=0xC000
code=[]; labels={}; fix=[]
def L(n): labels[n]=org+len(code)
def b(*x): code.extend(x)
def w(n): fix.append((len(code),n)); code.extend([0,0])
def jr(op,n): fix.append((len(code)+1,('rel',n))); code.extend([op,0])
b(0xF3)                         # DI
b(0x3E,0xC1,0xED,0x47,0xED,0x5E) # LD A,C1h; LD I,A; IM 2
b(0x21); w('HT'); b(0x22,0x04,0xC1)  # level 2 timer
b(0x21); w('HV'); b(0x22,0x02,0xC1)  # level 1 VRTC
b(0x21,0,0,0x22,0x00,0xC2,0x22,0x02,0xC2)
b(0xCD); w('SYNC')
b(0x3E,0x03,0xD3,0xE4,0xD3,0xE6,0xFB)  # E4=3, E6=3 (timer, VRTC), EI
b(0x06,60)
L('LP'); b(0xCD); w('SYNC'); jr(0x10,'LP')
b(0xF3,0xAF,0xD3,0xE6,0xFB,0xC9)       # DI; E6=0; EI; RET
L('SYNC'); b(0xDB,0x40,0xE6,0x20); jr(0x20,'SYNC')
L('S2'); b(0xDB,0x40,0xE6,0x20); jr(0x28,'S2'); b(0xC9)
L('HT'); b(0xE5,0x2A,0x00,0xC2,0x23,0x22,0x00,0xC2); jr(0x18,'COM')
L('HV'); b(0xE5,0x2A,0x02,0xC2,0x23,0x22,0x02,0xC2)
L('COM'); b(0xF5,0x3E,0x03,0xD3,0xE4,0xF1,0xE1,0xFB,0xED,0x4D)
for pos,n in fix:
    if isinstance(n,tuple):
        code[pos]=(labels[n[1]]-(org+pos+1))&0xFF
    else:
        code[pos]=labels[n]&0xFF; code[pos+1]=labels[n]>>8
print(''.join('%02X'%x for x in code))
