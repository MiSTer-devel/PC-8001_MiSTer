#!/usr/bin/env python3
# SR GVRAM ALU test (tools/cscp_suite.sh sralu): prints machine code (at C000h) as hex. Fills the planes as
# tools/srg_asm.py, then with 33h bit 6 and 35h bit 7 (the ALU window), each on its own band of lines:
#   8000-87FF  35h mode 0: 34h = 21h (B set, R invert, G clear) with data F0h
#   8800-8FFF  mode 1: copy the pixels latched by reading 9000h+ (all three planes)
#   9800-9FFF  mode 2: R to B (read then write each byte)
#   A000-A7FF  mode 3: B to R
#   A800-AFFF  read: compare with colour 5 (35h bits 2-0), kept in RAM D000h, then written to plane B B000h+
# then 640x200 colour (31h = 18h) and spins.
c = []
def b(*x): c.extend(x)
def out(port, v): b(0x3E, v, 0xD3, port)
def block(src, dst, n, body):
    b(0x21, src & 0xFF, src >> 8, 0x11, dst & 0xFF, dst >> 8, 0x01, n & 0xFF, n >> 8)
    loop = len(c)
    b(*body)
    b(0x23, 0x13, 0x0B, 0x78, 0xB1)
    b(0x20, (loop - (len(c) + 2)) & 0xFF)
b(0xF3)
for port, op in ((0x5C, [0x7D]), (0x5D, [0x7D, 0xAC]), (0x5E, [0x7C, 0x07, 0x07])):
    b(0xD3, port)
    block(0x8000, 0x8000, 0x4000, op + [0x77])
b(0xD3, 0x5F)
out(0x33, 0xC0)                                  # N80SR ROM + ALU window
out(0x34, 0x21); out(0x35, 0x80)
block(0x8000, 0x8000, 0x800, [0x3E, 0xF0, 0x77])  # LD A,F0h; LD (HL),A
out(0x35, 0x90)
block(0x9000, 0x8800, 0x800, [0x7E, 0x12])        # LD A,(HL); LD (DE),A
out(0x35, 0xA0)
block(0x9800, 0x9800, 0x800, [0x7E, 0x77])
out(0x35, 0xB0)
block(0xA000, 0xA000, 0x800, [0x7E, 0x77])
out(0x35, 0x85)
block(0xA800, 0xD000, 0x800, [0x7E, 0x12])
out(0x33, 0x80)
b(0xD3, 0x5C)
block(0xD000, 0xB000, 0x800, [0x7E, 0x12])
b(0xD3, 0x5F)
out(0x53, 0x00); out(0x31, 0x18)
b(0x18, 0xFE)
print(''.join('%02X' % x for x in c))
