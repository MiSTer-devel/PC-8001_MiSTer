// Next-step hint for the tape overlay (~/dev2/tape-standard.md rules 25-28): what to type to load and start
// the tape, read from the tape's own headers as the image downloads (never from the file name).
//
// The bytes the 8251 will see (a .cmt whole; a .t88's data tags, 101h, after their 12-byte header) are scanned
// for the first file and the start of the second:
//   BASIC (CSAVE): ten D3h, a 6-byte name (printable or 00h), the program, which ends with a line's 00h and a
//     0000h link: the first 00 00 00. Hint: TYPE CLOAD"name" <ret> at the tape's start, TYPE RUN <ret> once it
//     has loaded.
//   Machine code (monitor W): 3Ah, address hi, lo, checksum (the three add to 0), then records 3Ah, length,
//     data, checksum, up to a record of length 0. Hint: TYPE MON <ret> L <ret> at the start, nothing after:
//     the start address (G) is not on the tape, and "the first load address" fails for some tapes (Check
//     Point, Circuit), so it is not shown (rule 25). Nor is a second L for a second block: the monitor stops
//     the motor well after a block's end (Moon Alien at 5x: 55 bytes into the next block's header), so the
//     next L would not find that header.
// RUN is not shown when a machine-code block follows the BASIC program: some such programs load it themselves
// (Kumo Vader, Qix), others need MON, L, Ctrl+B first (Galaxian 1980, Marine Belt, Deep Scan: Neo Kobe's
// "{cload X mon L}"), and nothing on the tape tells them apart (69 of the 107 BASIC tapes).
// A first header that is neither (Pac Land's sides B-D, its own loader's blocks) gives no hint at all. RUN
// shows only while the tape sits past the BASIC program's end and no more than 64 bytes into the next file
// (CLOAD stops the motor a few bytes after the end: Kumo Vader 8, River Patrol 8, at 5x; rule 26), and is
// removed by Return; after that nothing more is shown until the tape is mounted again or rewound (a
// program that loads the rest of its tape itself, such as a BASIC loader, is not followed).
// Known tapes (rtl/tape_db.svh, generated by tools/tape_db.py from tools/tape_db.txt): a tape whose data
// bytes' length and CRC-16 are in the table (its content, not its name) gets the table's lines instead: for
// each zone, at the start or past its k-th file (up to 64 bytes into the next, as RUN above), the commands its
// notes give (G9000, CTRL+B RUN, CLEAR..., a second L), one line after another, each until its Returns (or
// its Ctrl+B) have been pressed. The scan follows up to 8 files for these zones.
// Offsets are image offsets, as the player's position (rtl/pc8001_cmt.sv ptr).

module tape_hint
(
	input             clk,

	input             ioctl_download,
	input       [7:0] ioctl_index,
	input             ioctl_wr,
	input      [24:0] ioctl_addr,
	input       [7:0] ioctl_dout,

	input             loaded,
	input             motor,
	input             rewind,
	input      [19:0] position,
	input      [10:0] ps2_key,

	output            show,
	output    [175:0] text          // 22 characters, first in bits 175-168; 01h = Return
);

wire tape_dl = ioctl_download & (ioctl_index[5:0] == 6'd1);
wire is_t88  = ioctl_index[7:6] == 2'd1;

//----------------------------------------------------------------------------
// .t88 tags -> data bytes
//----------------------------------------------------------------------------

reg  [2:0] tk = 0;              // tag header byte
reg [15:0] tid = 0, tln = 0;
reg [15:0] tleft = 0;           // body bytes left
reg        tbody = 0, tdata = 0;
reg        old_dl = 0;

wire       wr = tape_dl & ioctl_wr & (ioctl_addr[24:20] == 0);
wire       dbyte = wr & (is_t88 ? (tbody & tdata & (tln - tleft >= 16'd12)) : 1'b1);

always @(posedge clk) begin
	old_dl <= tape_dl;
	if (tape_dl & ~old_dl) begin tk <= 0; tbody <= 0; end
	else if (wr & is_t88 & (ioctl_addr >= 25'd24)) begin
		if (!tbody) begin
			case (tk)
			3'd0: tid[7:0]  <= ioctl_dout;
			3'd1: tid[15:8] <= ioctl_dout;
			3'd2: tln[7:0]  <= ioctl_dout;
			default: ;
			endcase
			tk <= tk + 1'd1;
			if (tk == 3'd3) begin
				tk <= 0;
				if ({ioctl_dout, tln[7:0]} != 0) begin
					tln[15:8] <= ioctl_dout;
					tleft <= {ioctl_dout, tln[7:0]};
					tbody <= 1;
					tdata <= tid == 16'h0101;
				end
			end
		end
		else begin
			tleft <= tleft - 1'd1;
			if (tleft == 16'd1) tbody <= 0;
		end
	end
end

//----------------------------------------------------------------------------
// Files: up to 8, each its start and end; the first one's kind and name
//----------------------------------------------------------------------------

localparam K_NONE = 2'd0, K_BASIC = 2'd1, K_MON = 2'd2;
localparam S_FIND = 3'd0, S_NAME = 3'd1, S_PROG = 3'd2, S_REC = 3'd4, S_DONE = 3'd5;
localparam NF = 8;

reg  [2:0] s = S_DONE;
reg  [3:0] nf = 0;              // files found
reg  [1:0] k1 = K_NONE;
reg [19:0] fs [0:NF];           // file k's start; fs[nf]: the next file's start, or the end of the tape
reg [19:0] fe [0:NF-1];         // file k's last byte
reg        f2_mc = 0;           // the second file is a machine-code block
reg  [7:0] name [0:5];
reg  [3:0] d3 = 0;              // D3h run (saturates at 10)
reg [19:0] d3_at = 0;
reg  [2:0] n = 0;
reg  [1:0] zeros = 0;
reg  [7:0] mh [0:3];            // machine-code header candidate
reg  [2:0] mk = 0;
reg [19:0] m_at = 0;
reg  [1:0] rp = 0;              // record part: 0 colon, 1 length, 2 data, 3 checksum
reg  [7:0] rlen = 0, rcnt = 0;
reg        rlast = 0;
reg [19:0] dlen = 0;            // data bytes
reg [15:0] crc = 0;             // CRC-16 (CCITT, from FFFFh) of the data bytes

// the data bytes, a clock late: the reset at the download's start comes first even if its first byte is
// written on the same clock
reg        pv = 0;
reg        fin = 0;             // the download has ended: close the file list once the last byte is in
reg        scanned = 0;         // pulse: the file list and the fingerprint are complete
reg  [7:0] pd = 0;
reg [19:0] at = 0;
always @(posedge clk) begin pv <= dbyte; pd <= ioctl_dout; at <= ioctl_addr[19:0]; end
wire       printable = (pd >= 8'h20 && pd < 8'h7F) || pd == 8'h00;

function automatic [15:0] crc_byte(input [15:0] c, input [7:0] d);
	reg [15:0] r;
	r = c ^ {d, 8'h00};
	for (int i = 0; i < 8; i++) r = r[15] ? {r[14:0], 1'b0} ^ 16'h1021 : {r[14:0], 1'b0};
	return r;
endfunction

task file_end;
	fe[nf[2:0]] <= at;
	nf <= nf + 1'd1;
	d3 <= 0; mk <= 0;
	if (nf == NF - 1) begin fs[NF] <= 20'hFFFFF; s <= S_DONE; end
	else s <= S_FIND;
endtask

always @(posedge clk) begin
	scanned <= 0;
	if (~tape_dl & old_dl) fin <= 1;
	if (tape_dl & ~old_dl) begin
		s <= S_FIND; nf <= 0; k1 <= K_NONE; f2_mc <= 0; d3 <= 0; mk <= 0; fin <= 0;
		dlen <= 0; crc <= 16'hFFFF;
	end
	else if (fin & ~pv) begin
		fin <= 0;
		scanned <= 1;
		if (s != S_DONE) begin
			fs[nf] <= at + 1'd1;        // no further file: the end of the tape (the last byte's address + 1)
			s <= S_DONE;
		end
	end
	else if (pv) begin
		dlen <= dlen + 1'd1;
		crc <= crc_byte(crc, pd);
		// D3h runs and machine-code headers are watched while looking for a file
		if (s == S_FIND) begin
			if (pd == 8'hD3) begin
				if (d3 == 0) d3_at <= at;
				if (d3 != 4'd10) d3 <= d3 + 1'd1;
			end
			else d3 <= 0;
			if (d3 == 4'd10 && pd != 8'hD3) begin
				// the name's first byte
				fs[nf] <= d3_at;
				if (printable) begin
					if (nf == 0) begin k1 <= K_BASIC; name[0] <= pd; end
					n <= 1; s <= S_NAME;
				end
				else s <= S_DONE;   // not a CSAVE header: the list ends (the first file: no hint for this tape)
				mk <= 0;
			end
			else begin
				// 3Ah hi lo sum 3Ah
				case (mk)
				3'd0: if (pd == 8'h3A) begin mk <= 1; m_at <= at; end
				3'd1, 3'd2, 3'd3: begin mh[mk[1:0]] <= pd; mk <= mk + 1'd1; end
				default: begin
					mk <= 0;
					if (pd == 8'h3A && (mh[1] + mh[2] + mh[3]) == 8'd0) begin
						// the 3Ah that confirmed the header is the first record's colon
						fs[nf] <= m_at;
						if (nf == 0) k1 <= K_MON;
						if (nf == 1) f2_mc <= 1;
						rp <= 1; s <= S_REC;
					end
					else if (pd == 8'h3A) begin mk <= 1; m_at <= at; end
				end
				endcase
			end
		end
		else case (s)
		S_NAME: begin
			if (printable) begin
				if (nf == 0) name[n] <= pd;
				n <= n + 1'd1;
				if (n == 3'd5) begin s <= S_PROG; zeros <= 0; end
			end
			else begin
				if (nf == 0) k1 <= K_NONE;
				s <= S_DONE;
			end
		end
		S_PROG: begin
			if (pd == 8'h00) begin
				zeros <= zeros + 1'd1;
				if (zeros == 2'd2) file_end;
			end
			else zeros <= 0;
		end
		S_REC: begin
			case (rp)
			2'd0: if (pd == 8'h3A) rp <= 1; else s <= S_DONE;
			2'd1: begin rlen <= pd; rcnt <= 0; rlast <= pd == 0; rp <= pd == 0 ? 2'd3 : 2'd2; end
			2'd2: begin rcnt <= rcnt + 1'd1; if (rcnt + 1'd1 == rlen) rp <= 3; end
			2'd3: begin
				rp <= 0;
				if (rlast) file_end;
			end
			endcase
		end
		default: ;
		endcase
	end
end

//----------------------------------------------------------------------------
// Known tapes (rtl/tape_db.svh, from tools/tape_db.txt): found by their data's length and CRC
//----------------------------------------------------------------------------

`include "tape_db.svh"

reg  [7:0] lk_i = 0;
reg        lk_run = 0, lk_vd = 0;
reg [49:0] lk_row = 0;
reg        known = 0;
reg  [9:0] k_first = 0;
reg  [3:0] k_cnt = 0;

always @(posedge clk) begin
	lk_row <= db_tape(lk_i);                    // a ROM: one entry a clock
	lk_vd <= lk_run;
	if (tape_dl) begin known <= 0; lk_run <= 0; lk_vd <= 0; end
	else begin
		if (scanned) begin lk_i <= 0; lk_run <= 1; end
		else if (lk_run) begin
			if (lk_i == 8'(DB_TAPES - 1)) lk_run <= 0;
			lk_i <= lk_i + 1'd1;
		end
		if (lk_vd && lk_row[49:30] == dlen && lk_row[29:14] == crc) begin
			known <= 1; k_first <= lk_row[13:4]; k_cnt <= lk_row[3:0];
		end
	end
end

//----------------------------------------------------------------------------
// When
//----------------------------------------------------------------------------

reg        fresh = 0;           // mounted or rewound, the motor not started since
reg        done = 0;            // Return pressed after the second step
reg        old_tog = 0, old_loaded = 0;
reg        ctrl = 0;
wire       kev = ps2_key[10] != old_tog;
wire       ret = kev & ps2_key[9] & (ps2_key[7:0] == 8'h5A);                          // Return or keypad Enter
wire       ctrlb = kev & ps2_key[9] & ~ps2_key[8] & (ps2_key[7:0] == 8'h32) & ctrl;   // Ctrl+B
wire       remount = (loaded & ~old_loaded) | rewind | tape_dl;

// the core's own hint (any tape): its first file's load command at the start, RUN after a BASIC program
wire       at_start = fresh || position <= fs[0];
wire       after1 = !fresh && nf != 0 && position > fe[0] && position <= fs[1] + 20'd64;
wire       step1 = at_start && k1 != K_NONE;
wire       step2 = after1 && !done && k1 == K_BASIC && !f2_mc;

always @(posedge clk) begin
	old_tog <= ps2_key[10];
	old_loaded <= loaded;
	if (kev && ps2_key[7:0] == 8'h14) ctrl <= ps2_key[9];                              // either Ctrl
	if (remount) begin fresh <= 1; done <= 0; end
	else if (motor) fresh <= 0;
	if (ret & step2 & ~motor) done <= 1;
end

// a known tape: zone k = past its k-th file (0 = at its start); the zone's lines one after another, each
// until its Returns / Ctrl+Bs have been pressed
reg  [3:0] zone;
reg        zone_v;
always @* begin
	zone_v = at_start; zone = 0;
	if (!fresh)
		for (int k = 1; k <= NF; k++)
			if (k <= nf && position > fe[k - 1] && {1'b0, position} <= {1'b0, fs[k]} + 21'd64) begin
				zone_v = 1; zone = 4'(k);
			end
end

reg  [9:0] cur = 0;
reg [142:0] row = 0;
reg  [3:0] czone = 0;
reg        cz_v = 0, seek = 0, wait1 = 0, zdone = 0, old_known = 0;
reg  [2:0] ev = 0;
wire [2:0] row_zone = row[142:140];
wire       row_last = row[139];
wire [2:0] row_ev = row[138:136];

always @(posedge clk) begin
	row <= db_line(cur);                        // a ROM, a clock behind cur
	old_known <= known;
	if (remount | (known & ~old_known) | ({zone_v, zone} != {cz_v, czone})) begin
		czone <= zone; cz_v <= zone_v;
		cur <= k_first; seek <= 1; wait1 <= 1; ev <= 0; zdone <= 0;
	end
	else if (seek) begin
		if (wait1) wait1 <= 0;
		else if ({1'b0, row_zone} == czone) seek <= 0;
		else if ({1'b0, row_zone} > czone || cur == k_first + 10'(k_cnt) - 1'd1) begin seek <= 0; zdone <= 1; end
		else begin cur <= cur + 1'd1; wait1 <= 1; end
	end
	else if ((ret | ctrlb) & ~motor & cz_v & ~zdone) begin
		if (ev + 1'd1 >= row_ev) begin
			ev <= 0;
			if (row_last) zdone <= 1;
			else begin cur <= cur + 1'd1; seek <= 1; wait1 <= 1; end
		end
		else ev <= ev + 1'd1;
	end
end

wire       show_known = cz_v && !seek && !zdone && row_ev != 0;

assign show = loaded && !motor && (known ? show_known : (step1 || step2));

//----------------------------------------------------------------------------
// What
//----------------------------------------------------------------------------

function automatic [7:0] nm(input [7:0] c);
	return c == 8'h00 ? 8'h20 : c;
endfunction

// name length without trailing spaces / 00h
reg [2:0] nlen;
always @* begin
	nlen = 0;
	for (int i = 0; i < 6; i++) if (name[i] != 8'h20 && name[i] != 8'h00) nlen = 3'(i + 1);
end

reg [7:0] t [0:21];
always @* begin
	for (int i = 0; i < 22; i++) t[i] = 8'h20;
	{t[0], t[1], t[2], t[3]} = "TYPE";
	if (known) begin
		for (int i = 0; i < 17; i++) t[5 + i] = row[135 - 8 * i -: 8];
	end
	else if (step1 && k1 == K_BASIC) begin
		{t[5], t[6], t[7], t[8], t[9], t[10]} = "CLOAD\"";
		for (int i = 0; i < 6; i++) if (i < nlen) t[11 + i] = nm(name[i]);
		t[11 + nlen] = 8'h22;
		t[13 + nlen] = 8'h01;
	end
	else if (step1) begin
		{t[5], t[6], t[7]} = "MON";  t[9] = 8'h01;  t[11] = "L";  t[13] = 8'h01;
	end
	else begin
		{t[5], t[6], t[7]} = "RUN";  t[9] = 8'h01;
	end
end

genvar g;
generate for (g = 0; g < 22; g++) begin : pk
	assign text[175 - 8 * g -: 8] = t[g];
end endgenerate

endmodule
